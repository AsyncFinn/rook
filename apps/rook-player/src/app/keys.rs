#[cfg(test)]
mod tests {
    use winit::keyboard::KeyCode as K;

    /// Every mapped name is a real Enum.KeyCode item.
    #[test]
    fn names_exist_in_the_key_code_enum() {
        let e = rook_reflection::database().enum_by_name("KeyCode").unwrap();
        let all = [
            K::KeyA,
            K::Digit7,
            K::Space,
            K::Enter,
            K::Escape,
            K::Backspace,
            K::Tab,
            K::ShiftLeft,
            K::ShiftRight,
            K::ControlLeft,
            K::ControlRight,
            K::AltLeft,
            K::AltRight,
            K::SuperLeft,
            K::SuperRight,
            K::CapsLock,
            K::ArrowUp,
            K::Insert,
            K::Delete,
            K::Home,
            K::End,
            K::PageUp,
            K::PageDown,
            K::Minus,
            K::Equal,
            K::BracketLeft,
            K::BracketRight,
            K::Backslash,
            K::Semicolon,
            K::Quote,
            K::Comma,
            K::Period,
            K::Slash,
            K::Backquote,
            K::F1,
            K::F12,
            K::Numpad0,
            K::NumpadEnter,
            K::NumpadAdd,
            K::NumpadSubtract,
            K::NumpadMultiply,
            K::NumpadDivide,
            K::NumpadDecimal,
        ];
        for k in all {
            let name = super::roblox_key(k).unwrap();
            assert!(
                e.items.iter().any(|(n, _)| *n == name),
                "{name} is not a KeyCode"
            );
        }
    }
}
