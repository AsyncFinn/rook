//! Thumbnails: images Roblox renders of assets, avatars, badges and the
//! rest, named by `rbxthumb://` or by the old web URLs Studio still loads
//! (`docs/behavior/content/thumbnails.md`). Every form is parsed here into
//! one [`Thumbnail`], the request the thumbnails service answers
//! (`resolver::thumbnails`), so each form loads wherever an image does.

use std::fmt;

/// What a thumbnail shows: the `type` of `rbxthumb://` and of the
/// thumbnails service's batch requests, which share their names.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum ThumbnailKind {
    Asset,
    AutoGeneratedAsset,
    Avatar,
    AvatarBust,
    AvatarHeadShot,
    BadgeIcon,
    BundleThumbnail,
    DeveloperProduct,
    FontFamily,
    GameIcon,
    GamePass,
    GameThumbnail,
    GroupIcon,
    Outfit,
}

/// Square sizes, as `(width, height)`.
macro_rules! squares {
    ($($n:literal),*) => { &[$(($n, $n)),*] };
}

impl ThumbnailKind {
    pub const ALL: [Self; 14] = [
        Self::Asset,
        Self::AutoGeneratedAsset,
        Self::Avatar,
        Self::AvatarBust,
        Self::AvatarHeadShot,
        Self::BadgeIcon,
        Self::BundleThumbnail,
        Self::DeveloperProduct,
        Self::FontFamily,
        Self::GameIcon,
        Self::GamePass,
        Self::GameThumbnail,
        Self::GroupIcon,
        Self::Outfit,
    ];

    pub fn name(self) -> &'static str {
        match self {
            Self::Asset => "Asset",
            Self::AutoGeneratedAsset => "AutoGeneratedAsset",
            Self::Avatar => "Avatar",
            Self::AvatarBust => "AvatarBust",
            Self::AvatarHeadShot => "AvatarHeadShot",
            Self::BadgeIcon => "BadgeIcon",
            Self::BundleThumbnail => "BundleThumbnail",
            Self::DeveloperProduct => "DeveloperProduct",
            Self::FontFamily => "FontFamily",
            Self::GameIcon => "GameIcon",
            Self::GamePass => "GamePass",
            Self::GameThumbnail => "GameThumbnail",
            Self::GroupIcon => "GroupIcon",
            Self::Outfit => "Outfit",
        }
    }

    /// The kind `rbxthumb://` names, case and all (`type=asset` loads
    /// nothing in Studio).
    pub fn from_name(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|k| k.name() == name)
    }

    /// The sizes an `rbxthumb://` of this kind may ask for. Measured in
    /// Studio 0.747 against every size the thumbnails service serves for
    /// any kind; the service itself takes more (an Asset at 30x30), which
    /// Studio refuses without asking.
    pub fn sizes(self) -> &'static [(u32, u32)] {
        match self {
            Self::Asset => &[
                (150, 150),
                (256, 144),
                (384, 216),
                (420, 420),
                (480, 270),
                (700, 700),
                (768, 432),
            ],
            Self::AutoGeneratedAsset
            | Self::BundleThumbnail
            | Self::DeveloperProduct
            | Self::GroupIcon
            | Self::Outfit => squares!(150, 420),
            Self::Avatar => squares!(48, 60, 100, 150, 180, 352, 420, 720),
            Self::AvatarBust => squares!(48, 50, 60, 75, 100, 150, 180, 352, 420),
            Self::AvatarHeadShot => squares!(48, 60, 100, 150, 180, 352, 420),
            Self::BadgeIcon | Self::GamePass => squares!(150),
            Self::FontFamily => &[(1200, 80)],
            Self::GameIcon => squares!(50, 128, 150, 256, 512),
            Self::GameThumbnail => &[(256, 144), (384, 216), (480, 270), (576, 324), (768, 432)],
        }
    }

    /// Whether the id is a user's.
    pub fn of_user(self) -> bool {
        matches!(self, Self::Avatar | Self::AvatarBust | Self::AvatarHeadShot)
    }
}

/// Whose thumbnail.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Target {
    Id(u64),
    /// A user by name (the old avatar URLs' `username=`), looked up when
    /// the thumbnail is fetched. Only letters, digits and underscores, as
    /// Roblox names are: anything else names no one.
    Username(String),
}

/// A thumbnail request: what of whom, at what size.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Thumbnail {
    pub kind: ThumbnailKind,
    pub target: Target,
    pub width: u32,
    pub height: u32,
    /// `filters=circular`: the image cut to a circle.
    pub circular: bool,
}

impl Thumbnail {
    /// `rbxthumb://<rest>`. Measured: keys in any case, the first of a
    /// repeated key wins, `type` exactly as named, ids and sizes read like
    /// asset ids (spaces, `+` and leading zeros are fine), and `w` and `h`
    /// one of the kind's [`sizes`](ThumbnailKind::sizes); other keys are
    /// ignored. Anything else loads nothing, so it is no content.
    pub(super) fn from_rbxthumb(rest: &str) -> Option<Self> {
        let kind = ThumbnailKind::from_name(first(rest, "type")?)?;
        let number = |key| first(rest, key).and_then(super::id_value);
        let size = (
            u32::try_from(number("w")?).ok()?,
            u32::try_from(number("h")?).ok()?,
        );
        if !kind.sizes().contains(&size) {
            return None;
        }
        Some(Self {
            kind,
            target: Target::Id(number("id")?),
            width: size.0,
            height: size.1,
            circular: first(rest, "filters") == Some("circular"),
        })
    }

    /// An old web URL's path and query (`Game/Tools/ThumbnailAsset.ashx?
    /// aid=5&wd=420&ht=420`), whatever its host: Studio never asks the
    /// host, it turns the URL into a thumbnail request itself (Roblox's own
    /// site answers 404 for all of these now).
    pub(super) fn from_web(path_and_query: &str) -> Option<Self> {
        let (path, query) = path_and_query.split_once('?')?;
        // Doubled slashes are fine; a trailing one isn't (measured).
        if path.ends_with('/') {
            return None;
        }
        let path: Vec<&str> = path.split('/').filter(|p| !p.is_empty()).collect();
        let form = WEB_FORMS.iter().find(|f| {
            let want: Vec<&str> = f.path.split('/').collect();
            want.len() == path.len()
                && want
                    .iter()
                    .zip(&path)
                    .all(|(a, b)| a.eq_ignore_ascii_case(b))
        })?;
        let size = |keys: &[&str]| {
            keys.iter()
                .find_map(|k| first(query, k))
                .and_then(size_value)
        };
        let (width, height) = (size(&WIDTH)?, size(&HEIGHT)?);
        let target = match form.username.and_then(|key| first(query, key)) {
            Some(name) => Target::Username(username(name)?),
            None => Target::Id(
                form.ids
                    .iter()
                    .find_map(|k| first(query, k))
                    .and_then(super::id_value)?,
            ),
        };
        let (width, height) = snap(form.sizes, width, height);
        Some(Self {
            kind: form.kind,
            target,
            width,
            height,
            circular: false,
        })
    }

    /// The disk cache's key: kind, target, size and filter.
    pub fn cache_key(&self) -> String {
        let target = match &self.target {
            Target::Id(id) => id.to_string(),
            Target::Username(name) => format!("user-{}", name.to_ascii_lowercase()),
        };
        let circular = if self.circular { "-circular" } else { "" };
        format!(
            "thumb-{}-{target}-{}x{}{circular}",
            self.kind.name(),
            self.width,
            self.height
        )
    }
}

impl fmt::Display for Thumbnail {
    /// `rbxthumb://` for an id; for a username, the old URL it came from.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let (kind, width, height) = (self.kind.name(), self.width, self.height);
        match &self.target {
            Target::Id(id) => write!(f, "rbxthumb://type={kind}&id={id}&w={width}&h={height}")?,
            Target::Username(name) => {
                let path = WEB_FORMS
                    .iter()
                    .find(|w| w.kind == self.kind && w.username.is_some())
                    .map_or("", |w| w.path);
                write!(
                    f,
                    "https://www.roblox.com/{path}?username={name}&width={width}&height={height}"
                )?;
            }
        }
        if self.circular {
            f.write_str("&filters=circular")?;
        }
        Ok(())
    }
}

/// An old thumbnail URL Studio loads, by its path.
struct WebForm {
    /// Compared ignoring case.
    path: &'static str,
    kind: ThumbnailKind,
    /// The id's keys, the first found winning.
    ids: &'static [&'static str],
    /// The username's key, which wins over the id (measured: a bad
    /// `username` fails with a good `userId` either side of it).
    username: Option<&'static str>,
    /// The square sizes asked sizes snap to.
    sizes: &'static [u32],
}

/// Square sizes the old asset URLs snap to (measured: 285 gives 150, 286
/// 420, 560 420, 561 700, 1000 700, and 20 to 130 all 150).
const ASSET_SNAP: &[u32] = &[150, 420, 700];
/// The thumbnails service's own sizes for these kinds (its
/// `v1/users/avatar*` endpoints take exactly these), which the old
/// avatar URLs snap to (measured: 30 gives 30, 75 75, 110 110, 165 150,
/// 200 180, 300 352, 400 420, 600 and 1000 720).
const AVATAR_SNAP: &[u32] = &[30, 48, 60, 75, 100, 110, 140, 150, 180, 250, 352, 420, 720];
const HEADSHOT_SNAP: &[u32] = &[48, 50, 60, 75, 100, 110, 150, 180, 352, 420, 720];
const BUST_SNAP: &[u32] = &[48, 50, 60, 75, 100, 150, 180, 352, 420];
const OUTFIT_SNAP: &[u32] = &[150, 420];

const ASSET_IDS: &[&str] = &["assetid", "aid"];
const USER_IDS: &[&str] = &["userid"];

/// Measured in Studio 0.747; other paths (`thumbs/headshot.ashx`,
/// `Thumbs/GroupIcon.ashx`, `badge-thumbnail/image`, `group-thumbnail/
/// image`) load nothing.
const WEB_FORMS: &[WebForm] = &[
    WebForm {
        path: "Game/Tools/ThumbnailAsset.ashx",
        kind: ThumbnailKind::Asset,
        ids: ASSET_IDS,
        username: None,
        sizes: ASSET_SNAP,
    },
    WebForm {
        path: "thumbs/asset.ashx",
        kind: ThumbnailKind::Asset,
        ids: ASSET_IDS,
        username: None,
        sizes: ASSET_SNAP,
    },
    WebForm {
        path: "asset-thumbnail/image",
        kind: ThumbnailKind::Asset,
        ids: ASSET_IDS,
        username: None,
        sizes: ASSET_SNAP,
    },
    WebForm {
        path: "avatar-thumbnail/image",
        kind: ThumbnailKind::Avatar,
        ids: USER_IDS,
        username: Some("username"),
        sizes: AVATAR_SNAP,
    },
    WebForm {
        path: "thumbs/avatar.ashx",
        kind: ThumbnailKind::Avatar,
        ids: USER_IDS,
        username: Some("username"),
        sizes: AVATAR_SNAP,
    },
    WebForm {
        path: "headshot-thumbnail/image",
        kind: ThumbnailKind::AvatarHeadShot,
        ids: USER_IDS,
        username: Some("username"),
        sizes: HEADSHOT_SNAP,
    },
    WebForm {
        path: "bust-thumbnail/image",
        kind: ThumbnailKind::AvatarBust,
        ids: USER_IDS,
        username: Some("username"),
        sizes: BUST_SNAP,
    },
    WebForm {
        path: "outfit-thumbnail/image",
        kind: ThumbnailKind::Outfit,
        ids: &["useroutfitid"],
        username: None,
        sizes: OUTFIT_SNAP,
    },
];

/// The size keys, in any form and mixed (`wd=420&y=420` loads); `w` and
/// `h` aren't among them.
const WIDTH: [&str; 3] = ["width", "wd", "x"];
const HEIGHT: [&str; 3] = ["height", "ht", "y"];

/// The size nearest the asked one, the smaller on a tie. Both sides
/// together, as their mean.
// TODO: Studio picks something else for sides that differ (150 by 420 gave
// an image larger than 150 and smaller than 420; 1000 by 1 a wide one);
// measure it with the ImageRectSize method in thumbnails.md.
fn snap(sizes: &[u32], width: i64, height: i64) -> (u32, u32) {
    let asked = (width + height) / 2;
    let best = sizes
        .iter()
        .copied()
        .min_by_key(|&s| (i64::from(s) - asked).abs())
        .expect("every form has sizes");
    (best, best)
}

/// A size as the old URLs take it: an integer, signed (`wd=-5` loads, at
/// the smallest size), with spaces around it.
fn size_value(value: &str) -> Option<i64> {
    let digits = value.trim();
    let unsigned = digits.strip_prefix(['+', '-']).unwrap_or(digits);
    if unsigned.is_empty() || !unsigned.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    digits.parse().ok()
}

fn username(name: &str) -> Option<String> {
    let name = name.trim();
    (!name.is_empty() && name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'))
        .then(|| name.to_owned())
}

/// The value of `key` in `key=value&key=value`, ignoring the key's case;
/// for a repeated key, the first (measured for both `rbxthumb://` and the
/// old URLs, where asset URLs take the last).
fn first<'a>(query: &'a str, key: &str) -> Option<&'a str> {
    query
        .split('&')
        .filter_map(|pair| pair.split_once('='))
        .find(|(k, _)| k.trim().eq_ignore_ascii_case(key))
        .map(|(_, v)| v)
}

