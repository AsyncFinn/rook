//! Rook's own defaults: a table of the 2009 client's `rbxasset://` paths
//! that modern installs lack, mapped to the public assets modern Studio
//! fetches for them (`docs/behavior/content/asset-fetching.md`, "The 2009
//! client's paths"). Rook ships no files: material textures come from
//! Roblox like any asset ([`crate::materials`]), and the head mesh is built
//! in code by `rook-render`.

/// The asset that stands in for a legacy `rbxasset://` path, compared
/// without case.
pub fn legacy_asset(path: &str) -> Option<u64> {
    LEGACY_PATHS
        .iter()
        .find(|(p, _)| p.eq_ignore_ascii_case(path))
        .map(|&(_, id)| id)
}

